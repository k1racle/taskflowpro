/**
 * Форматировать дату
 * @param {string|Date} date - Дата
 * @returns {string} - Форматированная дата
 */
function formatDate(date) {
    if (!date) return '—';
    const d = new Date(date);
    return d.toLocaleDateString('ru-RU', { 
        day: 'numeric', 
        month: 'long', 
        year: 'numeric' 
    });
}

/**
 * Форматировать время таймера
 * @param {number} seconds - Секунды
 * @returns {string} - Форматированное время
 */
function formatTimer(seconds) {
    if (!seconds) return '0:00';
    const mins = Math.floor(seconds / 60);
    const secs = seconds % 60;
    return `${mins}:${secs.toString().padStart(2, '0')}`;
}

/**
 * Проверить просрочен ли срок
 * @param {string|Date} deadline - Дедлайн
 * @returns {boolean} - true если просрочено
 */
function isOverdue(deadline) {
    if (!deadline) return false;
    return new Date(deadline) < new Date();
}

/**
 * Форматировать размер файла
 * @param {number} bytes - Размер в байтах
 * @returns {string} - Форматированный размер
 */
function formatFileSize(bytes) {
    if (!bytes) return '0 B';
    const k = 1024;
    const sizes = ['B', 'KB', 'MB', 'GB'];
    const i = Math.floor(Math.log(bytes) / Math.log(k));
    return Math.round(bytes / Math.pow(k, i) * 100) / 100 + ' ' + sizes[i];
}

/**
 * Проверить является ли файл изображением
 * @param {string} filename - Имя файла
 * @returns {boolean} - true если изображение
 */
function isImage(filename) {
    if (!filename) return false;
    const ext = filename.split('.').pop().toLowerCase();
    return ['jpg', 'jpeg', 'png', 'gif', 'webp', 'svg', 'bmp'].includes(ext);
}

